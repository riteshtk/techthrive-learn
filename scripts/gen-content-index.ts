// Writes content/.generated/index.ts, importing every roadmap and topic file,
// so adding a topic never means editing a hand-kept list.
// Files starting with "_" (such as the topic template) are skipped.
import { mkdirSync, readdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const root = join(import.meta.dirname, "..");

function list(dir: string): string[] {
  return readdirSync(join(root, "content", dir))
    .filter((f) => f.endsWith(".ts") && !f.startsWith("_"))
    .map((f) => f.slice(0, -3))
    .sort();
}

const topics = list("topics");
const roadmaps = list("roadmaps");

const lines = [
  "// Generated by scripts/gen-content-index.ts. Do not edit.",
  'import type { Roadmap, Topic } from "../types";',
  ...topics.map((id, i) => `import t${i} from "../topics/${id}";`),
  ...roadmaps.map((id, i) => `import r${i} from "../roadmaps/${id}";`),
  "",
  "export const topicFiles: { file: string; topic: Topic }[] = [",
  ...topics.map(
    (id, i) => `  { file: "content/topics/${id}.ts", topic: t${i} },`,
  ),
  "];",
  "",
  "export const roadmapFiles: { file: string; roadmap: Roadmap }[] = [",
  ...roadmaps.map(
    (id, i) => `  { file: "content/roadmaps/${id}.ts", roadmap: r${i} },`,
  ),
  "];",
  "",
];

mkdirSync(join(root, "content", ".generated"), { recursive: true });
writeFileSync(
  join(root, "content", ".generated", "index.ts"),
  lines.join("\n"),
);
console.log(
  `content index: ${topics.length} topics, ${roadmaps.length} roadmaps`,
);
