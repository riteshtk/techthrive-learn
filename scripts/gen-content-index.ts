// Writes the content indexes, importing every content file, so adding a
// topic, lesson or fact file never means editing a hand-kept list. Files and
// folders starting with "_" (templates) are skipped.
//
// - content/.generated/index.ts: v2 topics (content/topics/<id>/topic.ts),
//   their lessons, checkpoints and diagrams, and the facts register
//   (content/facts).
// - content/v1/.generated/index.ts: the v1 topics and roadmaps, until
//   Foundations replaces them.
import { existsSync, mkdirSync, readdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const root = join(import.meta.dirname, "..");

function tsFiles(dir: string): string[] {
  const full = join(root, dir);
  if (!existsSync(full)) return [];
  return readdirSync(full)
    .filter((f) => f.endsWith(".ts") && !f.startsWith("_"))
    .map((f) => f.slice(0, -3))
    .sort();
}

function folders(dir: string): string[] {
  const full = join(root, dir);
  if (!existsSync(full)) return [];
  return readdirSync(full, { withFileTypes: true })
    .filter((d) => d.isDirectory() && !d.name.startsWith("_"))
    .map((d) => d.name)
    .sort();
}

function write(dir: string, lines: string[]) {
  mkdirSync(join(root, dir, ".generated"), { recursive: true });
  writeFileSync(join(root, dir, ".generated", "index.ts"), lines.join("\n"));
}

// v2 -----------------------------------------------------------------------

type Entry = { file: string; name: string };
const topics: Entry[] = [];
const lessons: Entry[] = [];
const checkpoints: Entry[] = [];
const diagrams: Entry[] = [];
const tools: Entry[] = [];
for (const id of folders("content/topics")) {
  if (existsSync(join(root, "content/topics", id, "topic.ts")))
    topics.push({ file: `content/topics/${id}/topic.ts`, name: id });
  for (const l of tsFiles(`content/topics/${id}/lessons`))
    lessons.push({ file: `content/topics/${id}/lessons/${l}.ts`, name: l });
  for (const d of tsFiles(`content/topics/${id}/diagrams`))
    diagrams.push({ file: `content/topics/${id}/diagrams/${d}.ts`, name: d });
  for (const t of tsFiles(`content/topics/${id}/tools`))
    tools.push({ file: `content/topics/${id}/tools/${t}.ts`, name: t });
  for (const c of tsFiles(`content/topics/${id}/checkpoints`))
    checkpoints.push({
      file: `content/topics/${id}/checkpoints/${c}.ts`,
      name: c,
    });
}
const facts: Entry[] = tsFiles("content/facts").map((f) => ({
  file: `content/facts/${f}.ts`,
  name: f,
}));

const importOf = (prefix: string) => (e: Entry, i: number) =>
  `import ${prefix}${i} from "../${e.file.slice("content/".length, -3)}";`;
const listOf = (prefix: string, items: Entry[]) =>
  items.map((e, i) => `  { file: "${e.file}", data: ${prefix}${i} },`);

write("content", [
  "// Generated by scripts/gen-content-index.ts. Do not edit.",
  ...topics.map(importOf("t")),
  ...lessons.map(importOf("l")),
  ...checkpoints.map(importOf("c")),
  ...diagrams.map(importOf("d")),
  ...tools.map(importOf("x")),
  ...facts.map(importOf("f")),
  "",
  "// Each file's default export, unchecked: content/validate.ts checks it.",
  "export const topicFiles: { file: string; data: unknown }[] = [",
  ...listOf("t", topics),
  "];",
  "export const lessonFiles: { file: string; data: unknown }[] = [",
  ...listOf("l", lessons),
  "];",
  "export const checkpointFiles: { file: string; data: unknown }[] = [",
  ...listOf("c", checkpoints),
  "];",
  "export const diagramFiles: { file: string; data: unknown }[] = [",
  ...listOf("d", diagrams),
  "];",
  "export const factFiles: { file: string; data: unknown }[] = [",
  ...listOf("f", facts),
  "];",
  "export const toolFiles: { file: string; data: unknown }[] = [",
  ...listOf("x", tools),
  "];",
  "",
]);

// v1 -----------------------------------------------------------------------

const v1Topics = tsFiles("content/v1/topics");
const v1Roadmaps = tsFiles("content/v1/roadmaps");
write("content/v1", [
  "// Generated by scripts/gen-content-index.ts. Do not edit.",
  'import type { Roadmap, Topic } from "../types";',
  ...v1Topics.map((id, i) => `import t${i} from "../topics/${id}";`),
  ...v1Roadmaps.map((id, i) => `import r${i} from "../roadmaps/${id}";`),
  "",
  "export const topicFiles: { file: string; topic: Topic }[] = [",
  ...v1Topics.map(
    (id, i) => `  { file: "content/v1/topics/${id}.ts", topic: t${i} },`,
  ),
  "];",
  "",
  "export const roadmapFiles: { file: string; roadmap: Roadmap }[] = [",
  ...v1Roadmaps.map(
    (id, i) => `  { file: "content/v1/roadmaps/${id}.ts", roadmap: r${i} },`,
  ),
  "];",
  "",
]);

console.log(
  `content index: ${topics.length} topics, ${lessons.length} lessons, ` +
    `${checkpoints.length} checkpoints, ${diagrams.length} diagrams, ` +
    `${facts.length} fact files ` +
    `(v1: ${v1Topics.length} topics, ${v1Roadmaps.length} roadmaps)`,
);
