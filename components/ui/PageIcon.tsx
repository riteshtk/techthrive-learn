export type PageIconName = keyof typeof PATHS;

/** A decorative icon, as Icon, from the page-only set. */
export function PageIcon({ name }: { name: PageIconName }) {
  return (
    <svg
      className="tt-ic tt-ic-s"
      viewBox="0 0 24 24"
      aria-hidden="true"
      focusable="false"
    >
      <path d={PATHS[name]} />
    </svg>
  );
}

/** For server components that pick icons by name from either set. Client
    components use Icon, so these paths stay out of their bundles. */
export function AnyIcon({ name }: { name: IconName | PageIconName }) {
  const d =
    name in PATHS ? PATHS[name as PageIconName] : ICON_PATHS[name as IconName];
  return (
    <svg
      className="tt-ic tt-ic-s"
      viewBox="0 0 24 24"
      aria-hidden="true"
      focusable="false"
    >
      <path d={d} />
    </svg>
  );
}
